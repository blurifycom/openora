// A template file that is renamed or dropped must not linger in a consumer as an untracked
// stray that rulesync keeps generating from. Render the template into a throwaway consumer
// whose last render still listed such files, and check the stale ones go and the rest stay.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, test } from 'node:test';
import { fileURLToPath } from 'node:url';

const template = fileURLToPath(new URL('../templates/consumer/', import.meta.url));
const consumer = mkdtempSync(join(tmpdir(), 'sync-agents-'));
after(() => rmSync(consumer, { recursive: true, force: true }));

const put = (path, content) => {
  mkdirSync(dirname(join(consumer, path)), { recursive: true });
  writeFileSync(join(consumer, path), content);
};
const git = (...args) => execFileSync('git', args, { cwd: consumer, stdio: 'ignore' });

test('a file the template no longer renders is deleted, unless the consumer tracks it', () => {
  put('node_modules/@openora/create/package.json', '{"name":"@openora/create"}');
  symlinkSync(template, join(consumer, 'node_modules/@openora/create/template'));
  put('.rulesync/sync.json', JSON.stringify({ vars: { trackerKey: 'XX' } }));
  put('.rulesync/skills/add-feature/SKILL.md', 'old');
  put('.rulesync/subagents/qa.md', 'old');
  put('.rulesync/subagents/kept.md', 'mine');
  put('notes.md', 'outside the synced roots');
  put(
    '.gitignore',
    [
      '/node_modules',
      '# BEGIN synced-agents (generated by tools/sync-agents.mjs - do not edit)',
      '/.rulesync/skills/add-feature/SKILL.md',
      '/.rulesync/subagents/kept.md',
      '/.rulesync/subagents/qa.md',
      '/notes.md',
      '# END synced-agents',
      '',
    ].join('\n'),
  );
  git('init', '-q');
  git('add', '-f', '.rulesync/subagents/kept.md');

  execFileSync('node', [join(template, 'tools/sync-agents.mjs')], {
    cwd: consumer,
    stdio: 'ignore',
  });

  assert.equal(existsSync(join(consumer, '.rulesync/skills/add-feature')), false);
  assert.equal(existsSync(join(consumer, '.rulesync/subagents/qa.md')), false);
  assert.equal(readFileSync(join(consumer, '.rulesync/subagents/kept.md'), 'utf8'), 'mine');
  assert.equal(readFileSync(join(consumer, 'notes.md'), 'utf8'), 'outside the synced roots');
  assert.ok(existsSync(join(consumer, '.rulesync/skills/ship/SKILL.md')));
  assert.ok(existsSync(join(consumer, '.rulesync/subagents/tester.md')));
  assert.match(
    readFileSync(join(consumer, '.gitignore'), 'utf8'),
    /^\/\.rulesync\/subagents\/planner\.md$/m,
  );
});
